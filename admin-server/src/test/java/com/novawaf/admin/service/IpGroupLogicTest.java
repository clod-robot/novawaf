package com.novawaf.admin.service;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import org.junit.jupiter.api.Test;

import java.nio.charset.StandardCharsets;
import java.util.List;

import static org.junit.jupiter.api.Assertions.*;

/**
 * IpGroupService 纯逻辑单测（无 Spring 依赖）：
 * 条目校验、黑白名单整组合并、novawaf:ioc 文本重建、cksum 算法对齐。
 */
class IpGroupLogicTest {

    // ---------------- normalizeEntry ----------------

    @Test
    void normalizeEntryAcceptsIpAndCidr() {
        assertEquals("1.2.3.4", IpGroupService.normalizeEntry(" 1.2.3.4 "));
        assertEquals("10.0.0.0/24", IpGroupService.normalizeEntry("10.0.0.0/24"));
        assertEquals("192.168.1.7/31", IpGroupService.normalizeEntry("192.168.1.7/31"));
    }

    @Test
    void normalizeEntryRejectsGarbage() {
        assertNull(IpGroupService.normalizeEntry(null));
        assertNull(IpGroupService.normalizeEntry(""));
        assertNull(IpGroupService.normalizeEntry("   "));
        assertNull(IpGroupService.normalizeEntry("# 注释行"));
        assertNull(IpGroupService.normalizeEntry("not-an-ip"));
        assertNull(IpGroupService.normalizeEntry("999.1.1.1"));
        assertNull(IpGroupService.normalizeEntry("1.2.3.4/33"));
        assertNull(IpGroupService.normalizeEntry("DROP TABLE users"));
    }

    // ---------------- mergeIpListJson ----------------

    @Test
    void mergeReplacesGroupEntriesKeepingOthers() throws Exception {
        // 同 id 组（group:7）的旧条目被整组替换；其它来源（manual / 别的组 group:2）保留
        String current = "[{\"id\":\"m1\",\"ip\":\"1.1.1.1\",\"type\":\"black\",\"source\":\"manual\","
                + "\"note\":\"手动\",\"enabled\":true,\"hits\":0,\"createdAt\":1,\"createdBy\":\"admin\"},"
                + "{\"id\":\"g7-1\",\"ip\":\"2.2.2.2\",\"type\":\"black\",\"source\":\"group:7\","
                + "\"note\":\"旧条目\",\"enabled\":true,\"hits\":0,\"createdAt\":1,\"createdBy\":\"ipgroup\"},"
                + "{\"id\":\"g2-1\",\"ip\":\"5.5.5.5\",\"type\":\"black\",\"source\":\"group:2\","
                + "\"note\":\"别的组\",\"enabled\":true,\"hits\":0,\"createdAt\":1,\"createdBy\":\"ipgroup\"}]";
        String merged = IpGroupService.mergeIpListJson(current, 7, "测试组", true,
                List.of("3.3.3.3", "10.0.0.0/8"), false);
        JsonNode arr = new ObjectMapper().readTree(merged);
        assertTrue(arr.isArray());
        assertEquals(4, arr.size());  // manual + 别的组 group:2 + 新组 2 条（旧 group:7 条目被替换掉）
        assertEquals("1.1.1.1", arr.get(0).path("ip").asText());
        assertEquals("group:2", arr.get(1).path("source").asText());
        assertEquals("group:7", arr.get(2).path("source").asText());
        assertEquals("black", arr.get(2).path("type").asText());
        assertEquals("10.0.0.0/8", arr.get(3).path("ip").asText());
        assertEquals("测试组", arr.get(3).path("note").asText());
    }

    @Test
    void mergeWithDisabledGroupOnlyStrips() throws Exception {
        String current = "[{\"ip\":\"2.2.2.2\",\"type\":\"black\",\"source\":\"group:2\"},"
                + "{\"ip\":\"1.1.1.1\",\"type\":\"black\",\"source\":\"manual\"}]";
        String merged = IpGroupService.mergeIpListJson(current, 2, "x", false, List.of("3.3.3.3"), false);
        JsonNode arr = new ObjectMapper().readTree(merged);
        assertEquals(1, arr.size());
        assertEquals("manual", arr.get(0).path("source").asText());
    }

    @Test
    void mergeWhiteChannelUsesWhiteType() throws Exception {
        String merged = IpGroupService.mergeIpListJson(null, 9, "放行组", true, List.of("192.168.1.0/24"), true);
        JsonNode arr = new ObjectMapper().readTree(merged);
        assertEquals(1, arr.size());
        assertEquals("white", arr.get(0).path("type").asText());
        assertEquals("group:9", arr.get(0).path("source").asText());
    }

    @Test
    void mergeHandlesBlankOrNullCurrent() throws Exception {
        JsonNode a = new ObjectMapper().readTree(IpGroupService.mergeIpListJson(null, 1, "g", true, List.of("1.1.1.1"), false));
        JsonNode b = new ObjectMapper().readTree(IpGroupService.mergeIpListJson("   ", 1, "g", true, List.of("1.1.1.1"), false));
        assertEquals(1, a.size());
        assertEquals(1, b.size());
        // 非法 JSON 必须抛异常（兜底为空会静默丢失手动名单条目，危险），由上层转 BusinessException
        assertThrows(Exception.class,
                () -> IpGroupService.mergeIpListJson("not-json", 1, "g", true, List.of("1.1.1.1"), false));
    }

    // ---------------- rebuildIocText ----------------

    @Test
    void rebuildIocKeepsForeignLinesAndRebuildsGroupLines() {
        String current = "# generated by ti_feed\n"
                + "ip,9.9.9.9,high,feed,外部情报\n"
                + "ip,2.2.2.2,high,ipgroup:5,旧组\n"
                + "cidr,10.0.0.0/8,medium,ipgroup:5,旧组\n";
        List<IpGroupService.GroupEntries> groups = List.of(
                new IpGroupService.GroupEntries(5, "威胁,组名", List.of("1.1.1.1", "10.0.0.0/8")));
        String out = IpGroupService.rebuildIocText(current, groups);
        String[] lines = out.split("\n");
        assertEquals(4, lines.length);  // 注释 + 外部 feed 行 + 新组 2 行
        assertEquals("# generated by ti_feed", lines[0]);
        assertEquals("ip,9.9.9.9,high,feed,外部情报", lines[1]);
        assertEquals("ip,1.1.1.1,high,ipgroup:5,威胁 组名", lines[2]);  // 组名中逗号已替换
        assertEquals("cidr,10.0.0.0/8,high,ipgroup:5,威胁 组名", lines[3]);  // 旧 ipgroup 行全部重建
    }

    @Test
    void rebuildIocDedupsAcrossGroups() {
        List<IpGroupService.GroupEntries> groups = List.of(
                new IpGroupService.GroupEntries(1, "A", List.of("1.1.1.1", "2.2.2.2")),
                new IpGroupService.GroupEntries(2, "B", List.of("1.1.1.1", "3.3.3.3")));
        String out = IpGroupService.rebuildIocText(null, groups);
        assertEquals(3, out.split("\n").length);
        assertTrue(out.contains("ipgroup:1"));
        assertTrue(out.contains("ipgroup:2"));
    }

    @Test
    void rebuildIocDistinguishesIpFromCidrOfSameValue() {
        List<IpGroupService.GroupEntries> groups = List.of(
                new IpGroupService.GroupEntries(1, "A", List.of("1.1.1.1", "1.1.1.1/32")));
        String out = IpGroupService.rebuildIocText(null, groups);
        assertTrue(out.contains("ip,1.1.1.1,"));
        assertTrue(out.contains("cidr,1.1.1.1/32,"));
        assertEquals(2, out.split("\n").length);
    }

    // ---------------- sha256Hex16（与 ti_feed.py / 引擎 loadDataLines 对齐） ----------------

    @Test
    void sha256PrefixMatchesReference() {
        // echo -n "hello" | sha256sum -> 2cf24dba5fb0a30e... 前 16 位
        assertEquals("2cf24dba5fb0a30e",
                IpGroupService.sha256Hex16("hello".getBytes(StandardCharsets.UTF_8)));
        assertEquals(16, IpGroupService.sha256Hex16(new byte[0]).length());
    }
}
